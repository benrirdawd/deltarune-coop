#!/usr/bin/env python3
"""Generates mod/hooks/handdrawn.hook from the decompiled code (work/chN/AllCode).

Cutscene objects (names with event, scene, cutscene or intro) that draw sprites or rectangles by
hand in their Draw event get those calls replaced by the mirror's wrappers (scr_mp_mirror:
mp_mir_dse, mp_mir_ds, mp_mir_drect): they draw as before, and in the leader's game what they draw
also goes to the friends watching the scene. Objects already handled in core.hook are left out.

Usage: python tools/gen_handdrawn.py   (after decompiling the chapters into work/chN/AllCode)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = re.compile(r"(event|scene|cutscene|intro)", re.I)
CALLS = [
    (r"\bdraw_sprite_ext\(", "mp_mir_dse("),
    (r"\bdraw_sprite\(", "mp_mir_ds("),
    (r"\bdraw_rectangle\(", "mp_mir_drect("),
    # (draw_self too, when the object also draws by hand: it then leaves the plain sprite list.)
    (r"\bdraw_self\(\)", "mp_mir_dself()"),
]
core = open(os.path.join(ROOT, "mod", "hooks", "core.hook"), encoding="utf-8").read()
# Kept scenery (scr_mp_mirror: mp_mirror_keep_init) draws itself in the watchers' games.
KEPT = {"obj_ch2_scene26_cityscape", "obj_ch2_scene26_gigaqueen", "obj_looping_tiled_area",
        "obj_anime_bg_controller", "obj_ch2_scene26_powers_combined", "obj_darkfountain", "obj_fountainkris",
        "obj_dw_gameshow_screen", "obj_quiz_podium", "obj_ch3_audience", "obj_ch3_GSA02_spotlight",
        "obj_dw_gameshow_stage_overlay", "obj_dw_tv_funometer",
        "obj_darkness_overlay", "obj_lightbeamfx", "obj_light_area_mask", "obj_light_following",
        "obj_lutshader", "obj_bg_palette_swap", "obj_fcastle_light", "obj_leafpetals"}

out = [";; Generated by tools/gen_handdrawn.py. Do not edit: run the script again.",
       ";; Cutscene objects that draw by hand: what they draw reaches the friends watching the scene",
       ";; (scr_mp_mirror: mp_mir_dse, mp_mir_ds, mp_mir_drect).", ""]
total = 0
for ch in range(1, 6):
    d = os.path.join(ROOT, "work", "ch%d" % ch, "AllCode")
    if not os.path.isdir(d):
        sys.exit("missing " + d)
    block = []
    for f in sorted(os.listdir(d)):
        m = re.match(r"gml_Object_(obj_\w+?)_Draw_0\.gml$", f)
        if not m:
            continue
        obj = m.group(1)
        if not NAME.search(obj) or obj in KEPT:
            continue
        entry = f[:-4]
        if re.search(r"^@\w+ " + re.escape(entry) + r"\s*$", core, re.M):
            continue
        code = open(os.path.join(d, f), encoding="utf-8", errors="replace").read()
        for pat, rep in CALLS:
            if re.search(pat, code) and (rep != "mp_mir_dself()" or any(re.search(p2, code) for p2, _ in CALLS[:3])):
                block += ["@regex " + entry, pat, "@with", rep, "@end"]
                total += 1
    if block:
        out += ["#chapters %d" % ch] + block + [""]
out.append("#chapters all")
open(os.path.join(ROOT, "mod", "hooks", "handdrawn.hook"), "w", encoding="utf-8", newline="\r\n").write("\n".join(out) + "\n")
print("handdrawn.hook:", total, "edits")
