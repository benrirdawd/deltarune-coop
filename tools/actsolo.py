# Usage: python tools/actsolo.py <repo root>  (needs work/chN/AllCode dumps and build/game lang files)
# Writes mod/gml/gml_GlobalScript_scr_mp_actsolo_chN.gml: the team ACTs that only take a helper's turn.
import re, os, sys, glob, json
root = sys.argv[1]
NAMES = {2: ['susie'], 3: ['ralsei'], 4: ['susie', 'ralsei'], 5: ['noelle']}
for ch in range(1, 6):
    d = f'{root}/work/ch{ch}/AllCode'
    lp = f'{root}/build/game/chapter{ch}_windows/lang/lang_en.json'
    lang = json.load(open(lp, encoding='utf-8')) if os.path.exists(lp) else {}
    ms = open(f'{d}/gml_GlobalScript_scr_monstersetup.gml', encoding='utf-8', errors='replace').read()
    es = open(f'{d}/gml_GlobalScript_scr_encountersetup.gml', encoding='utf-8', errors='replace').read()
    # monstertype -> enemy objects
    t2o = {}
    for m in re.finditer(r'monsterinstancetype\[(\d)\] = (obj_\w+);\s*\n\s*global\.monstertype\[\1\] = (\d+);', es):
        t2o.setdefault(int(m.group(3)), set()).add(m.group(2))
    # monstertype blocks -> actactor entries
    blocks = re.split(r'if \(global\.monstertype\[myself\] == (\d+)\)', ms)
    acts = {}
    for i in range(1, len(blocks), 2):
        t = int(blocks[i]); body = blocks[i + 1]
        for m in re.finditer(r'actactor\[myself\]\[(\d)\] = ([2-5]);', body):
            acts.setdefault(t, {})[int(m.group(1))] = int(m.group(2))
    ok, bad = [], []
    for t, a in sorted(acts.items()):
        for obj in sorted(t2o.get(t, [])):
            files = glob.glob(f'{d}/gml_Object_{obj}_*.gml')
            code = '\n'.join(open(f, encoding='utf-8', errors='replace').read() for f in files)
            # split into "if (acting == X" branches
            parts = re.split(r'(?=if \(acting == [\d.]+)', code)
            for ai, who in sorted(a.items()):
                k = ai + 1
                blk = ''
                for p in parts:
                    m = re.match(r'if \(acting == ([\d.]+)', p)
                    if not m: continue
                    x = float(m.group(1))
                    if int(x) == k or x >= 10:
                        blk += p
                if not blk:
                    bad.append((obj, ai, who, 'no code')); continue
                blk += ' '.join(str(lang.get(i, '')) for i in re.findall(r'"([A-Za-z0-9_]+_slash_[A-Za-z0-9_]+)"', blk))
                low = blk.lower()
                hit = [n for n in NAMES[who] if n in low]
                (bad if hit else ok).append((obj, ai, who, ','.join(hit)))
    print(f'ch{ch}: {len(ok)} turn-only, {len(bad)} need the hero', file=sys.stderr)
    with open(f'{root}/mod/gml/gml_GlobalScript_scr_mp_actsolo_ch{ch}.gml', 'w', newline='\n') as f:
        f.write(f'// @chapters {ch}\n')
        f.write('// Generated by tools/actsolo.py: Kris\'s team ACTs whose code never names the helper hero\n')
        f.write('// (no object, sprite or text of them), so they only take the helper\'s turn ("object:act").\n')
        f.write('function mp_act_solo_list()\n{\n    return [')
        f.write(', '.join(f'"{o}:{i}"' for o, i, w, h in ok))
        f.write('];\n}\n')
