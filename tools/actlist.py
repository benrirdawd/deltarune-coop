# Usage: python tools/actlist.py <repo root> > ACTS.md
# Lists Kris's team ACTs (actactor 2-5) per chapter and enemy, with what co-op does with each today.
# Same scan as tools/actsolo.py; a team ACT is "turn only" when its code never names the helper.
import re, os, sys, glob, json
root = sys.argv[1]
NAMES = {2: ['susie'], 3: ['ralsei'], 4: ['susie', 'ralsei'], 5: ['noelle']}
WHO = {2: 'Susie', 3: 'Ralsei', 4: 'Susie + Ralsei', 5: 'Noelle'}
out = []
for ch in range(1, 6):
    d = f'{root}/work/ch{ch}/AllCode'
    lp = f'{root}/build/game/chapter{ch}_windows/lang/lang_en.json'
    lang = json.load(open(lp, encoding='utf-8')) if os.path.exists(lp) else {}
    ms = open(f'{d}/gml_GlobalScript_scr_monstersetup.gml', encoding='utf-8', errors='replace').read()
    es = open(f'{d}/gml_GlobalScript_scr_encountersetup.gml', encoding='utf-8', errors='replace').read()
    t2o = {}
    for m in re.finditer(r'monsterinstancetype\[(\d)\] = (obj_\w+);\s*\n\s*global\.monstertype\[\1\] = (\d+);', es):
        t2o.setdefault(int(m.group(3)), set()).add(m.group(2))
    blocks = re.split(r'if \(global\.monstertype\[myself\] == (\d+)\)', ms)
    rows = {}
    for i in range(1, len(blocks), 2):
        t = int(blocks[i]); body = blocks[i + 1]
        mname = re.search(r'monstername\[myself\] = (?:stringsetloc\("([^"]*)"|scr_84_get_lang_string\("([^"]*)")', body)
        mname = (mname.group(1) or lang.get(mname.group(2), mname.group(2))) if mname else f'type {t}'
        names = {}
        for m in re.finditer(r'actname\[myself\]\[(\d)\] = (?:stringsetloc\("([^"]*)"|scr_84_get_lang_string\("([^"]*)"|"([^"]*)"|(\w+))', body):
            nm = m.group(2) or (m.group(3) and lang.get(m.group(3), m.group(3))) or m.group(4) or m.group(5)
            names.setdefault(int(m.group(1)), nm)
        acts = {}
        for m in re.finditer(r'actactor\[myself\]\[(\d)\] = ([2-5]);', body):
            acts[int(m.group(1))] = int(m.group(2))
        for obj in sorted(t2o.get(t, [])):
            files = glob.glob(f'{d}/gml_Object_{obj}_*.gml')
            code = '\n'.join(open(f, encoding='utf-8', errors='replace').read() for f in files)
            parts = re.split(r'(?=if \(acting == [\d.]+)', code)
            for ai, who in sorted(acts.items()):
                blk = ''
                for p in parts:
                    mm = re.match(r'if \(acting == ([\d.]+)', p)
                    if mm and (int(float(mm.group(1))) == ai + 1 or float(mm.group(1)) >= 10):
                        blk += p
                blk += ' '.join(str(lang.get(k, '')) for k in re.findall(r'"([A-Za-z0-9_]+_slash_[A-Za-z0-9_]+)"', blk))
                uses = any(n in blk.lower() for n in NAMES[who]) or not blk
                key = (mname, obj, ai)
                if key not in rows:
                    rows[key] = (names.get(ai, f'act {ai}'), who, 'needs a stand-in (Improvise)' if uses else 'works without the helper (takes only their turn)')
    out.append(f'\n## Chapter {ch}\n\n| Enemy | ACT | Helper | Today without the helper | With Noelle | With Berdly |\n|---|---|---|---|---|---|')
    for (mname, obj, ai), (an, who, st) in sorted(rows.items()):
        out.append(f'| {mname} (`{obj}`) | {an} | {WHO[who]} | {st} | | |')
print('# Team ACTs changed or to change for co-op\n')
print('Kris\'s ACTs that need another hero (generated by `tools/actlist.py`). For each: who it needs and what')
print('co-op does when that hero is not in the fight. When Noelle (and later Berdly) become playable in more')
print('fights, this is the list to go through: each ACT may get a version with them (cost ladder: full team')
print('cheapest, then a duo, then a solo stand-in, see TODO.md "Improvise").\n')
print('Special cases done by hand: Chapter 2 Queen with Berdly plugged in, Throw: without Kris, Susie\'s')
print('Improvise throws Ralsei (20% TP). The last game board\'s Tenna (`obj_tenna_board4_enemy`) works without')
print('the helpers.')
print('\n'.join(out))
